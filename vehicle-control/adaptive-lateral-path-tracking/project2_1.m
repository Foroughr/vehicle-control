%% ==========================================================
% Extract simulation outputs
% ==========================================================

yref_out  = out.yref_out;
y_out     = out.y_out;
ey_out    = out.ey_out;
delta_out = out.delta_out;
Chat_out  = out.Chat_out;
Vy_out    = out.Vy_out;
r_out     = out.r_out;
psi_out   = out.psi_out;

%% ==========================================================
% Calculate error indices
% ==========================================================

ey = ey_out.Data;
delta = delta_out.Data;
Chat = Chat_out.Data;

RMSE = sqrt(mean(ey.^2));
MaxError = max(abs(ey));
MeanError = mean(abs(ey));

FinalChat = Chat(end);
TrueC = 60000;

AbsEstError = abs(FinalChat - TrueC);
PercentEstError = 100 * AbsEstError / TrueC;

deltaMax = 0.25;
SaturationPercent = 100 * sum(abs(delta) >= 0.249) / length(delta);

fprintf('Vehicle speed = %.2f km/h\n', Vx*3.6);
fprintf('RMSE lateral error = %.4f m\n', RMSE);
fprintf('Maximum lateral error = %.4f m\n', MaxError);
fprintf('Mean absolute lateral error = %.4f m\n', MeanError);
fprintf('Final estimated C_alpha = %.2f N/rad\n', FinalChat);
fprintf('Absolute estimation error = %.2f N/rad\n', AbsEstError);
fprintf('Percentage estimation error = %.4f %%\n', PercentEstError);
fprintf('Steering saturation percentage = %.2f %%\n', SaturationPercent);

%% ==========================================================
% Plot 1: Path tracking response
% ==========================================================

figure;
plot(yref_out.Time, yref_out.Data, 'LineWidth', 1.8);
hold on;
plot(y_out.Time, y_out.Data, '--', 'LineWidth', 1.8);
grid on;
xlabel('Time (s)');
ylabel('Lateral position y (m)');
legend('Reference y_{ref}', 'Vehicle y', 'Location', 'best');
title(['Path Tracking Response at V_x = ', num2str(Vx*3.6), ' km/h']);

