grid on;
xlabel('Time (s)');
ylabel('Lateral error e_y = y - y_{ref} (m)');
title(['Lateral Tracking Error at V_x = ', num2str(Vx*3.6), ' km/h']);

%% ==========================================================
% Plot 3: Steering input with saturation limits
% ==========================================================

figure;
plot(delta_out.Time, delta_out.Data, 'LineWidth', 1.8);
hold on;
yline(deltaMax, '--', 'Upper saturation limit');
yline(-deltaMax, '--', 'Lower saturation limit');
grid on;
xlabel('Time (s)');
ylabel('Steering angle \delta_f (rad)');
title(['Steering Input Generated by STR at V_x = ', num2str(Vx*3.6), ' km/h']);
legend('\delta_f', '+\delta_{max}', '-\delta_{max}', 'Location', 'best');

